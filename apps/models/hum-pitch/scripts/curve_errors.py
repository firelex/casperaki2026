"""Where SwiftF0's pitch curve goes wrong today: compare it with the PERFORMED pitch curve (pitch.npz) of synthetic test clips.

  python -I scripts/curve_errors.py

pitch.npz holds the curve that drove the synthesiser (cents = 100 x MIDI every 10 ms, NaN where silent; for library
instruments the note pitch plus the recording's own measured contour). It is interpolated to SwiftF0's 16 ms
frames (a frame counts as voiced in the reference only when both neighbouring 10 ms points are voiced).
Per lead group (voice, breathy, instrument; SoulX singer apart): voicing recall and false alarms, and on frames
voiced in both: share within 50 cents, octave errors (within 50 cents of +-12 semitones), errors of 50-150 cents
(the ones that turn into semitone errors after rounding), other gross errors; median absolute error in cents.
Writes results/curve-errors.md.
"""
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HERE))
from hum_pitch.core import read_manifest  # noqa: E402
from hum_pitch.notes import load_curve  # noqa: E402


def clip_frames(row):
    times, midi, voiced, _ = load_curve(row["id"])
    with np.load(row["wav"][:-4] + ".pitch.npz") as z:
        rt, rc = z["time_s"], z["cents"] / 100.0
    v = np.isfinite(rc)
    idx = np.clip(np.searchsorted(rt, times), 1, len(rt) - 1)
    both = v[idx - 1] & v[idx]
    w = (times - rt[idx - 1]) / (rt[idx] - rt[idx - 1])
    ref = np.where(both, rc[idx - 1] * (1 - w) + rc[idx] * w, np.nan)
    inside = times <= rt[-1]
    return ref[inside], midi[inside], voiced[inside]


def main():
    rows = read_manifest("synth-test")
    groups = {}
    for r in rows:
        key = "voice: SoulX singer" if r["lead"] == "soulx" else r["group"]
        ref, est, v = clip_frames(r)
        g = groups.setdefault(key, {"ref_voiced": 0, "hit_voiced": 0, "ref_silent": 0, "false_voiced": 0, "d": []})
        rv = np.isfinite(ref)
        ev = v & np.isfinite(est)
        g["ref_voiced"] += int(rv.sum())
        g["hit_voiced"] += int((rv & ev).sum())
        g["ref_silent"] += int((~rv).sum())
        g["false_voiced"] += int((~rv & ev).sum())
        g["d"].append(est[rv & ev] - ref[rv & ev])
        g.setdefault("clips", 0)
        g["clips"] += 1
    lines = ["# SwiftF0 pitch curve vs the performed pitch curve (synthetic test, generated by scripts/curve_errors.py)", "",
             "| leads | clips | voicing recall | false voiced (of silent frames) | within 50 cents | octave err | 50-150 cents | other gross | median abs err (cents) |",
             "|---|---|---|---|---|---|---|---|---|"]
    out = {}
    for key in ("voice", "voice: SoulX singer", "breathy", "instrument"):
        g = groups[key]
        d = np.concatenate(g["d"])
        a = np.abs(d)
        octave = np.abs(np.abs(d) - 12) <= 0.5
        within = a <= 0.5
        semi = (a > 0.5) & (a <= 1.5)
        s = {"clips": g["clips"], "voicing_recall": g["hit_voiced"] / g["ref_voiced"], "false_voiced": g["false_voiced"] / g["ref_silent"],
             "within50": within.mean(), "octave": octave.mean(), "semi": semi.mean(), "other": (~within & ~semi & ~octave).mean(),
             "median_abs_cents": float(np.median(a) * 100)}
        out[key] = s
        lines.append(f"| {key} | {s['clips']} | {s['voicing_recall']:.1%} | {s['false_voiced']:.1%} | {s['within50']:.1%} | {s['octave']:.2%} | "
                     f"{s['semi']:.1%} | {s['other']:.2%} | {s['median_abs_cents']:.1f} |")
    (HERE / "results/curve-errors.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(json.dumps(out, indent=1))


if __name__ == "__main__":
    main()
