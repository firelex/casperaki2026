"""No training: the model's note boundaries, pitched by step 1's method.

  python -I scripts/combine.py --checkpoint <run>/final.pt --name <run name>

Notes come from the trained model's onset and activity outputs (decoding thresholds from
results/model-<name>-settings.json, chosen on humtrans-tune). Each note is then pitched as in step 1: the median
SwiftF0 pitch over the note's voiced frames, minus the recording's tuning offset (duration-weighted circular mean of
the notes' distance to the semitone grid), then snapped to the scale when it lies within 0.45 semitone of the midpoint
between two semitones (step 1's chosen margin). The scale comes from either the Krumhansl-Schmuckler key of the
tuned, rounded notes, or the model's key head (its key signature as a major scale). Writes results/combine-<name>.md.
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np
import torch

HERE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE / "scripts"))
from hum_pitch.core import clip_metrics  # noqa: E402
from hum_pitch.model import FRAME_S, decode, load_checkpoint  # noqa: E402
from hum_pitch.notes import Config, estimate_key, scale_set, tuning_offset  # noqa: E402
from score_model import load_set, pooled, run_model  # noqa: E402

MARGIN = Config(**json.loads((HERE / "results/notes-steps-settings.json").read_text())["key"]).snap_margin


def pitch_notes(feat, ref, notes, key_mode, key_probs):
    """notes [[on, off, midi_from_model], ...] -> [[on, off, midi_step1], ...]"""
    raw = []
    for on, off, _ in notes:
        a, b = int(round(on / FRAME_S)), int(round(off / FRAME_S))
        v = feat[a:b, 1] > 0.5
        m = float(np.median(feat[a:b, 0][v])) if v.any() else float(np.median(ref[a:b]))
        raw.append([on, off, m])
    if not raw:
        return []
    off_fn = tuning_offset(raw, Config(tuning="global"))
    tuned = [[a, b, m - float(off_fn(np.array([(a + b) / 2]))[0])] for a, b, m in raw]
    if key_mode == "none":
        return [[a, b, int(round(m))] for a, b, m in tuned]
    if key_mode == "ks":
        arr = np.asarray(tuned)
        sc = scale_set(*estimate_key(np.round(arr[:, 2]).astype(int), arr[:, 1] - arr[:, 0]))
    elif key_mode == "model":
        sc = scale_set(int(np.argmax(key_probs)), "major")
    else:
        raise ValueError(key_mode)
    out = []
    for a, b, m in tuned:
        lo = int(np.floor(m))
        p = int(round(m))
        if abs(m - lo - 0.5) <= MARGIN:
            cand = [x for x in (lo, lo + 1) if x % 12 in sc]
            if len(cand) == 1:
                p = cand[0]
        out.append([a, b, p])
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--checkpoint", type=Path, required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--extra-sets", nargs="*", default=[], help="more feature sets (e.g. r3-test), broken down by lead group")
    args = ap.parse_args()
    torch.set_num_threads(8)
    model = load_checkpoint(args.checkpoint)
    st = json.loads((HERE / f"results/model-{args.name}-settings.json").read_text())
    t_on, t_act = st["t_on"], st["t_act"]
    systems = ["model alone", "model notes + tuning offset", "model notes + tuning + key snap (Krumhansl-Schmuckler key)",
               "model notes + tuning + key snap (model's key head)"]
    md = [f"# Model note boundaries pitched by step 1's method (generated by scripts/combine.py)", "",
          f"Checkpoint `{args.checkpoint}`, decoding thresholds onset {t_on}, activity {t_act} (chosen on humtrans-tune for the model alone); "
          f"snap margin {MARGIN}. Today's best on HumTrans test: 71.2% right notes, precision 67.0%, F 0.691.", ""]
    for set_name, groups in (
        ("humtrans-test", [("all", lambda c: True), ("women", lambda c: c.get("sex") == "F"), ("men", lambda c: c.get("sex") == "M")]),
        ("synth-test", [("all", lambda c: True), ("voice", lambda c: c["group"] == "voice"), ("breathy", lambda c: c["group"] == "breathy"),
                        ("instrument", lambda c: c["group"] == "instrument"), ("round one", lambda c: c.get("round") == "r1"),
                        ("round two", lambda c: c.get("round") == "r2b")]),
    ) + tuple((x, [("all", lambda c: True), ("voice", lambda c: c["group"] == "voice"), ("breathy", lambda c: c["group"] == "breathy"),
                    ("instrument", lambda c: c["group"] == "instrument")]) for x in args.extra_sets):
        clips = load_set(set_name)
        outs = run_model(model, clips)
        rows = []
        for c, o in zip(clips, outs):
            notes = decode(o["onset"], o["active"], o["delta"], o["ref"], t_on, t_act)
            r = {"c": c, systems[0]: clip_metrics(c["ref_notes"], notes)}
            for sname, km in zip(systems[1:], ("none", "ks", "model")):
                r[sname] = clip_metrics(c["ref_notes"], pitch_notes(c["feat"], o["ref"], notes, km, o["key"]))
            rows.append(r)
        md += [f"### {set_name}", "", "| slice | system | clips | right note | precision | F (+-100 ms) | octave err | semitone err | other pitch err | missed |",
               "|---|---|---|---|---|---|---|---|---|---|"]
        for gname, sel in groups:
            sub = [r for r in rows if sel(r["c"])]
            for sname in systems:
                s = pooled([r[sname] for r in sub])
                md.append(f"| {gname} | {sname} | {s['clips']} | {s['right']:.1%} | {s['precision']:.1%} | {s['f100']:.3f} | {s['err_octave']:.1%} | "
                          f"{s['err_semitone']:.1%} | {s['err_other']:.1%} | {s['missed']:.1%} |")
        md.append("")
    (HERE / f"results/combine-{args.name}.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
