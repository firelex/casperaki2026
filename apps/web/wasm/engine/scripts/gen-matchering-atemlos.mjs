#!/usr/bin/env node
// Generates src/audio/MatcheringAtemlos.h: the data the legacy matchering port reads
// about its reference track "Atemlos", baked into the engine so the analysis needs no
// files at run time (and can run in the browser).
//
//   node scripts/gen-matchering-atemlos.mjs [atemlos.json] [referenceAtemlos.wav]
//
// Defaults: ../../../../../casperaki_engine/dependencies/matchering/Source/atemlos.json
//           ../../../../../casperaki_engine/assets/referenceAtemlos.wav
//
// What is taken from each file, and how it is converted (so the values are the very
// floats the JUCE original holds):
//  - atemlos.json: midFIRCoefficients / sideFIRCoefficients (8192 numbers each: the
//    reference's average FFT magnitude and phase per bin, interleaved) and RMSValue.
//    The original parses them with nlohmann::json into doubles and casts to float
//    (Helpers.h:880 readFFTCoefficientsFromJSON); Math.fround does the same rounding.
//  - referenceAtemlos.wav: only its peak is used (Matchering.h:225 matchLevels ->
//    Helpers.h:271 normalizeAudioBuffer -> finalAmplitudeCoefficient). JUCE reads
//    16-bit PCM as int16 << 16 times 1/0x7fffffff (= 2^-31 in float), i.e. int16 / 32768.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const engineRoot = path.resolve(here, '..');
const legacyRoot = path.resolve(engineRoot, '../../../../../casperaki_engine');
const jsonPath = process.argv[2] ?? path.join(legacyRoot, 'dependencies/matchering/Source/atemlos.json');
const wavPath = process.argv[3] ?? path.join(legacyRoot, 'assets/referenceAtemlos.wav');
const outPath = path.join(engineRoot, 'src/audio/MatcheringAtemlos.h');

const data = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
for (const key of ['midFIRCoefficients', 'sideFIRCoefficients']) {
  if (!Array.isArray(data[key]) || data[key].length !== 8192)
    throw new Error(`${jsonPath}: ${key} must be an array of 8192 numbers`);
}
if (typeof data.RMSValue !== 'number') throw new Error(`${jsonPath}: RMSValue missing`);

// Minimal RIFF walk: require 16-bit PCM, find the data chunk, take the peak.
const wav = fs.readFileSync(wavPath);
if (wav.toString('ascii', 0, 4) !== 'RIFF' || wav.toString('ascii', 8, 12) !== 'WAVE')
  throw new Error(`${wavPath}: not a RIFF/WAVE file`);
let off = 12, fmt = null, dataOff = -1, dataLen = 0;
while (off + 8 <= wav.length) {
  const id = wav.toString('ascii', off, off + 4);
  const len = wav.readUInt32LE(off + 4);
  if (id === 'fmt ') fmt = { format: wav.readUInt16LE(off + 8), channels: wav.readUInt16LE(off + 10),
                             rate: wav.readUInt32LE(off + 12), bits: wav.readUInt16LE(off + 22) };
  if (id === 'data') { dataOff = off + 8; dataLen = len; break; }
  off += 8 + len + (len & 1);
}
if (!fmt || fmt.format !== 1 || fmt.bits !== 16 || fmt.rate !== 44100 || dataOff < 0)
  throw new Error(`${wavPath}: expected 16-bit PCM 44.1 kHz with a data chunk, got ${JSON.stringify(fmt)}`);
let maxAbs = 0;
for (let i = dataOff; i + 1 < dataOff + dataLen; i += 2) maxAbs = Math.max(maxAbs, Math.abs(wav.readInt16LE(i)));
const peak = Math.fround(maxAbs / 32768);
const frames = dataLen / (2 * fmt.channels);

// 9 significant digits round-trip every float exactly.
const f = (v) => {
  const x = Math.fround(v);
  if (!Number.isFinite(x)) throw new Error(`non-finite value ${v}`);
  const s = x.toPrecision(9);
  return (s.includes('e') || s.includes('.') ? s : s + '.') + 'f';
};
const arr = (name, values) => {
  const lines = [];
  for (let i = 0; i < values.length; i += 8) lines.push('    ' + values.slice(i, i + 8).map(f).join(', ') + ',');
  return `inline const float ${name}[8192] = {\n${lines.join('\n')}\n};\n`;
};

const out = `// GENERATED by scripts/gen-matchering-atemlos.mjs — do not edit by hand.
// Reference-track data for the matchering port (src/audio/Matchering.h), taken from
//   ${path.relative(engineRoot, jsonPath)}
//   ${path.relative(engineRoot, wavPath)} (${frames} frames, ${fmt.channels} ch, peak |sample| ${maxAbs}/32768)
#pragma once

namespace casperaki {
namespace matchering {
namespace atemlos {

// Matchering.h:140 Matcherer ctor -> Helpers.h:880 readFFTCoefficientsFromJSON.
// Average FFT of the reference's loudest mid / side pieces: 4096 bins, each
// (magnitude, phase) interleaved.
${arr('kMidAverageFft', data.midFIRCoefficients)}
${arr('kSideAverageFft', data.sideFIRCoefficients)}
// Match RMS of the reference (Matchering.h:240 referenceMatchRMS = referenceRMSValue).
inline constexpr float kRmsValue = ${f(data.RMSValue)};

// Peak absolute sample of referenceAtemlos.wav as JUCE reads it (int16 / 32768).
inline constexpr float kReferencePeak = ${f(peak)};

} // namespace atemlos
} // namespace matchering
} // namespace casperaki
`;
fs.writeFileSync(outPath, out);
console.log(`wrote ${path.relative(process.cwd(), outPath)} (RMSValue ${f(data.RMSValue)}, peak ${f(peak)})`);
